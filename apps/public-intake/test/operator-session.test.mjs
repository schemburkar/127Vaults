import test from 'node:test';
import assert from 'node:assert/strict';
import { createOperatorSession, validOperatorSession, revokeOperatorSession, clearOperatorSession, memoryOperatorSessions } from '../src/operator-session.mjs';
test('operator cookie expires absolutely after one hour, is signed and rotates with the key', async () => {
  const at = 1792240000000, secret = 'a'.repeat(43);
  const sessions = memoryOperatorSessions();
  const cookie = await createOperatorSession(secret, at, sessions);
  const other = await createOperatorSession(secret, at, sessions);
  assert.match(cookie, /HttpOnly; Secure; SameSite=Strict/);
  assert.match(cookie, /Path=\/api\/access-admin; Max-Age=3600/);
  assert.equal(await validOperatorSession(cookie, secret, at + 3599999, sessions), true);
  assert.equal(await validOperatorSession(cookie, secret, at + 3600000, sessions), false);
  assert.equal(await validOperatorSession(cookie, 'b'.repeat(43), at, sessions), false);
  assert.equal(await validOperatorSession(cookie.replace(/=\d/, '=0'), secret, at, sessions), false);
  assert.equal(await validOperatorSession('', secret, at, sessions), false);
  await revokeOperatorSession(cookie, secret, at, sessions);
  assert.equal(await validOperatorSession(cookie, secret, at, sessions), false);
  assert.equal(await validOperatorSession(other, secret, at, sessions), true);
  assert.match(clearOperatorSession(), /Max-Age=0/);
});
